CREATE TABLE IF NOT EXISTS customer_accounts (
    customer_account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_salt BYTEA NOT NULL,
    password_hash BYTEA NOT NULL,
    preferences JSONB NOT NULL DEFAULT '{"textSize":100,"highContrast":false}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT customer_accounts_email_normalized
        CHECK (email = lower(btrim(email))),
    CONSTRAINT customer_accounts_preferences_object
        CHECK (jsonb_typeof(preferences) = 'object')
);

ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS customer_account_id INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'orders_customer_account_id_fkey'
          AND conrelid = 'orders'::regclass
    ) THEN
        ALTER TABLE orders
            ADD CONSTRAINT orders_customer_account_id_fkey
            FOREIGN KEY (customer_account_id)
            REFERENCES customer_accounts(customer_account_id);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS orders_customer_account_id_idx
    ON orders (customer_account_id, order_id DESC);
